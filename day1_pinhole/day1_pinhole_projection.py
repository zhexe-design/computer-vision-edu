import numpy as np
import cv2


# ============================================================
# ШАГ 1. Создаём простую 3D-сцену
# ============================================================

# 3D-точки: вершины куба + начало координат
points_3d = np.array([
    [0, 0, 0],  # начало координат
    [1, 0, 0],  # X
    [0, 1, 0],  # Y
    [0, 0, 1],  # Z
    [1, 1, 0],
    [1, 0, 1],
    [0, 1, 1],
    [1, 1, 1]
], dtype=np.float32)


# ============================================================
# ШАГ 2. Задаём параметры камеры (Intrinsic)
# ============================================================

# Размер изображения
width = 640
height = 480

# Внутренняя матрица камеры K
fx = 800
fy = 800

cx = width / 2
cy = height / 2

K = np.array([
    [fx, 0, cx],
    [0, fy, cy],
    [0, 0, 1]
], dtype=np.float32)


# ============================================================
# ШАГ 3. Задаём положение камеры (Extrinsic)
# ============================================================

# Вектор вращения камеры
rvec = np.array(
    [0.5, 0.5, 0.0],
    dtype=np.float32
)

# Вектор перемещения камеры
tvec = np.array(
    [0.0, 0.0, 4.0],
    dtype=np.float32
)


# ============================================================
# ШАГ 4. Проецируем 3D -> 2D
# ============================================================

# Проекция 3D-точек на изображение
points_2d, _ = cv2.projectPoints(
    points_3d,
    rvec,
    tvec,
    K,
    None
)

# Преобразуем результат в удобный формат
points_2d = points_2d.reshape(-1, 2)


# ============================================================
# ШАГ 5. Рисуем результат
# ============================================================

# Создаём белое изображение
img = np.ones(
    (height, width, 3),
    dtype=np.uint8
) * 255


# ------------------------------------------------------------
# Рисуем точки
# ------------------------------------------------------------

for pt in points_2d:
    x = int(pt[0])
    y = int(pt[1])

    cv2.circle(
        img,
        (x, y),
        6,
        (0, 0, 0),
        -1
    )


# ------------------------------------------------------------
# Рисуем оси координат
# ------------------------------------------------------------

origin = tuple(points_2d[0].astype(int))

# X — красная линия
cv2.line(
    img,
    origin,
    tuple(points_2d[1].astype(int)),
    (0, 0, 255),
    2
)

# Y — зелёная линия
cv2.line(
    img,
    origin,
    tuple(points_2d[2].astype(int)),
    (0, 255, 0),
    2
)

# Z — синяя линия
cv2.line(
    img,
    origin,
    tuple(points_2d[3].astype(int)),
    (255, 0, 0),
    2
)


# ============================================================
# Выводим результат
# ============================================================

cv2.imshow("Pinhole Projection", img)

# Сохраняем результат в файл
cv2.imwrite("result.png", img)

print("Проекция успешно выполнена!")
print("Результат сохранён в файл: result.png")

# Ждём нажатия клавиши
cv2.waitKey(0)

# Закрываем все окна OpenCV
cv2.destroyAllWindows()